    private void searchTask() {
        int selectedRow = tblTask.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a task");
            return;
        }

        String id = tblTask.getValueAt(selectedRow, 0).toString();
        try {
            TaskDto dto = taskController.searchTask(id);
            if (dto != null) {
                txtSubject.setText(dto.getSubject());
                txtDescription.setText(dto.getDescription());
                jDateChooser.setDate(java.sql.Date.valueOf(dto.getDeadline()));
            } else {
                JOptionPane.showMessageDialog(this, "Task Not Found");
            }
        } catch (Exception ex) {
            System.getLogger(DashboardView.class.getName())
                    .log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

    private void loadTasks() {
        try {
            ArrayList<TaskDto> tasks = taskController.getAllTasks();
            LocalDate today = LocalDate.now();

            loadTasksToTable(tasks);

            // Counters for weekly chart
            int completed = 0, overdue = 0, upcoming = 0;

            for (TaskDto task : tasks) {
                final AtomicReference<Color> baseColorRef = new AtomicReference<>();

                if (task.isCompleted()) {
                    baseColorRef.set(new Color(144, 238, 144)); // green
                    completed++;
                } else if (task.getDeadline().isBefore(today)) {
                    baseColorRef.set(new Color(255, 99, 71)); // red
                    overdue++;
                } else {
                    baseColorRef.set(new Color(255, 215, 0)); // yellow
                    upcoming++;
                }

                JPanel card = new JPanel() {
                    @Override
                    protected void paintComponent(Graphics g) {
                        Color baseColor = baseColorRef.get();
                        Graphics2D g2 = (Graphics2D) g;
                        g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
                        GradientPaint gp = new GradientPaint(0, 0, baseColor.brighter(), 0, getHeight(), baseColor.darker());
                        g2.setPaint(gp);
                        g2.fillRoundRect(0, 0, getWidth(), getHeight(), 20, 20);
                        super.paintComponent(g);
                    }
                };
                card.setOpaque(false);
                card.setLayout(new GridLayout(0, 1, 5, 5));
                card.setBorder(new EmptyBorder(15, 15, 15, 15));
                card.setMaximumSize(new Dimension(Integer.MAX_VALUE, 130));

                JLabel titleLabel = new JLabel(task.getSubject());
                titleLabel.setFont(new Font("Segoe UI Semibold", Font.BOLD, 16));
                titleLabel.setForeground(Color.DARK_GRAY);

                JLabel descriptionLabel = new JLabel("<html><b>Description:</b> " + task.getDescription() + "</html>");
                descriptionLabel.setFont(new Font("Segoe UI", Font.PLAIN, 14));

                JLabel deadlineLabel = new JLabel("<html><b>Deadline:</b> " + task.getDeadline() + "</html>");
                deadlineLabel.setFont(new Font("Segoe UI", Font.PLAIN, 14));

                JLabel countdownLabel = new JLabel("<html><b>Time left:</b> " + getTimeLeft(task.getDeadline()) + "</html>");
                countdownLabel.setFont(new Font("Segoe UI", Font.PLAIN, 14));
                if (!task.isCompleted() && task.getDeadline().isBefore(today.plusDays(1))) {
                    countdownLabel.setForeground(Color.RED.darker());
                }

                card.add(titleLabel);
                card.add(descriptionLabel);
                card.add(deadlineLabel);
                card.add(countdownLabel);

                if (!task.isCompleted()) {
                    JButton completeButton = new JButton("Mark as Complete");
                    completeButton.setFont(new Font("Segoe UI", Font.BOLD, 12));
                    completeButton.setForeground(Color.WHITE);
                    completeButton.setBackground(new Color(34, 139, 34));
                    completeButton.setFocusPainted(false);

                    completeButton.addActionListener(new ActionListener() {
                        @Override
                        public void actionPerformed(ActionEvent e) {
                            try {
                                task.setCompleted(true);
                                taskController.updateTask(task);
                                baseColorRef.set(new Color(144, 238, 144));
                                card.repaint();
                                card.remove(completeButton);
                                card.revalidate();
                                card.repaint();
                                showWellDonePopup(SwingUtilities.getWindowAncestor(Form1.this));
                            } catch (Exception ex) {
                                JOptionPane.showMessageDialog(Form1.this,
                                        "Error marking task as completed: " + ex.getMessage());
                            }
                        }
                    });

                    card.add(completeButton);
                }

                card.addMouseListener(new java.awt.event.MouseAdapter() {
                    public void mouseEntered(java.awt.event.MouseEvent evt) {
                        card.setCursor(new Cursor(Cursor.HAND_CURSOR));
                        baseColorRef.set(baseColorRef.get().brighter());
                        card.repaint();
                    }

                    public void mouseExited(java.awt.event.MouseEvent evt) {
                        if (task.isCompleted()) {
                            baseColorRef.set(new Color(144, 238, 144));
                        } else if (task.getDeadline().isBefore(today)) {
                            baseColorRef.set(new Color(255, 99, 71));
                        } else {
                            baseColorRef.set(new Color(255, 215, 0));
                        }
                        card.repaint();
                    }
                });

               
            }

            
 
           

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading tasks: " + e.getMessage());
            e.printStackTrace();
        }
    }

    private void updateWeeklyChart(int completed, int overdue, int upcoming) {
        weeklyChart.clearData();
        if (completed > 0) {
            weeklyChart.addData(new ModelPieChart("Completed", completed, new Color(144, 238, 144)));
        }
        if (overdue > 0) {
            weeklyChart.addData(new ModelPieChart("Overdue", overdue, new Color(255, 99, 71)));
        }
        if (upcoming > 0) {
            weeklyChart.addData(new ModelPieChart("Upcoming", upcoming, new Color(255, 215, 0)));
        }
        weeklyChart.repaint();
    }

    private void showWellDonePopup(Window parentWindow) {
        JWindow popup = new JWindow(parentWindow);
        popup.setLayout(new BorderLayout());

        ImageIcon icon = null;
        try {
            java.net.URL imgURL = getClass().getResource("thumbs-up.png");
            if (imgURL != null) {
                icon = new ImageIcon(imgURL);
                Image img = icon.getImage().getScaledInstance(40, 40, Image.SCALE_SMOOTH);
                icon = new ImageIcon(img);
            }
        } catch (Exception e) {
        }

        JLabel label = new JLabel("Well done!", SwingConstants.CENTER);
        label.setFont(new Font("Segoe UI", Font.BOLD, 18));
        label.setForeground(Color.WHITE);

        JPanel content = new JPanel(new FlowLayout(FlowLayout.CENTER, 10, 10));
        content.setBackground(new Color(34, 139, 34));
        content.setBorder(BorderFactory.createEmptyBorder(15, 30, 15, 30));

        if (icon != null) {
            content.add(new JLabel(icon));
        }
        content.add(label);
        popup.add(content, BorderLayout.CENTER);
        popup.pack();

        int x = parentWindow.getX() + parentWindow.getWidth() / 2 - popup.getWidth() / 2;
        int y = parentWindow.getY() + parentWindow.getHeight() / 2 - popup.getHeight() / 2;
        popup.setLocation(x, y);
        popup.setOpacity(0f);
        popup.setVisible(true);

        Timer fadeIn = new Timer(50, null);
        fadeIn.addActionListener(ev -> {
            float opacity = popup.getOpacity() + 0.1f;
            if (opacity >= 1f) {
                popup.setOpacity(1f);
                fadeIn.stop();
                new Timer(3000, ev2 -> startFadeOut(popup)).start();
            } else {
                popup.setOpacity(opacity);
            }
        });
        fadeIn.start();
    }

    private void startFadeOut(JWindow popup) {
        Timer fadeOut = new Timer(50, null);
        fadeOut.addActionListener(ev -> {
            float opacity = popup.getOpacity() - 0.1f;
            if (opacity <= 0f) {
                popup.setOpacity(0f);
                popup.setVisible(false);
                popup.dispose();
                fadeOut.stop();
            } else {
                popup.setOpacity(opacity);
            }
        });
        fadeOut.start();
    }

    private String getTimeLeft(LocalDate deadline) {
        LocalDateTime now = LocalDateTime.now();
        LocalDateTime end = deadline.atStartOfDay();
        if (deadline.equals(LocalDate.now())) {
            end = LocalDateTime.of(deadline.plusDays(1), java.time.LocalTime.MIDNIGHT);
        }

        if (end.isBefore(now)) {
            return "Expired";
        }

        Duration duration = Duration.between(now, end);
        long days = duration.toDays();
        long hours = duration.minusDays(days).toHours();
        long minutes = duration.minusDays(days).minusHours(hours).toMinutes();
        long seconds = duration.minusDays(days).minusHours(hours).minusMinutes(minutes).getSeconds();

        if (deadline.equals(LocalDate.now())) {
            return String.format("%02d hours, %02d mins, %02d secs", hours, minutes, seconds);
        } else {
            return String.format("%d days, %d hours, %d mins, %d secs", days, hours, minutes, seconds);
        }
    }

