    private void refreshCalendar() {
        colorCodeCalendar();     // Color days for tasks
        addDayButtonListeners(); // Add click listeners for each day
    }

    private void addDayButtonListeners() {
        JDayChooser dayChooser = jCalendar1.getDayChooser();

        // Iterate over day buttons
        for (Component c : dayChooser.getDayPanel().getComponents()) {
            if (c instanceof JButton button) {
                // Remove previous listeners (just in case)
                for (ActionListener al : button.getActionListeners()) {
                    button.removeActionListener(al);
                }

                // Add new listener
                button.addActionListener(e -> {
                    try {
                        int day = Integer.parseInt(button.getText());
                        int month = jCalendar1.getMonthChooser().getMonth() + 1;
                        int year = jCalendar1.getYearChooser().getYear();
                        LocalDate selectedDate = LocalDate.of(year, month, day);
                        showTasksInGlassPane(selectedDate);
                    } catch (NumberFormatException ex) {
                        // Skip buttons like empty placeholders
                    }
                });
            }
        }

        colorCodeCalendar();
    }

    private void colorCodeCalendar() {
        try {
            ArrayList<TaskDto> tasks = taskController.getAllTasks();
            var dayChooser = jCalendar1.getDayChooser();
            var dayButtons = dayChooser.getDayPanel().getComponents();

            // Reset buttons
            for (var c : dayButtons) {
                if (c instanceof javax.swing.JButton button) {
                    button.setBackground(Color.WHITE);
                    button.setToolTipText(null);
                }
            }

            LocalDate today = LocalDate.now();
            int currentMonth = jCalendar1.getMonthChooser().getMonth() + 1;

            for (TaskDto task : tasks) {
                LocalDate deadline = task.getDeadline();
                if (deadline.getMonthValue() == currentMonth
                        && deadline.getYear() == jCalendar1.getYearChooser().getYear()) {
                    int dayOfMonth = deadline.getDayOfMonth();
                    for (var c : dayButtons) {
                        if (c instanceof javax.swing.JButton button) {
                            try {
                                int buttonDay = Integer.parseInt(button.getText());
                                if (buttonDay == dayOfMonth) {
                                    if (task.isCompleted()) {
                                        button.setBackground(Color.GREEN);
                                    } else if (deadline.isBefore(today)) {
                                        button.setBackground(Color.RED);
                                    } else if (deadline.equals(today)) {
                                        button.setBackground(Color.ORANGE);
                                    } else {
                                        button.setBackground(Color.decode("#FFC900"));
                                    }
                                    button.setToolTipText(task.getSubject());
                                }
                            } catch (NumberFormatException ignored) {
                            }
                        }
                    }
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void showTasksInGlassPane(LocalDate selectedDate) {
        try {
            // Recolor calendar first
            colorCodeCalendar();

            // Get tasks for the selected date
            ArrayList<TaskDto> allTasks = taskController.getAllTasks();
            ArrayList<TaskDto> dayTasks = new ArrayList<>();

            for (TaskDto task : allTasks) {
                if (task.getDeadline().equals(selectedDate)) {
                    dayTasks.add(task);
                }
            }

            if (dayTasks.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No tasks for " + selectedDate);
                return;
            }

            // Create a panel to hold task cards in vertical layout
            JPanel popupPanel = new JPanel();
            popupPanel.setOpaque(false);
            popupPanel.setLayout(new GridBagLayout()); // for vertical stacking
            GridBagConstraints gbc = new GridBagConstraints();
            gbc.gridx = 0;
            gbc.gridy = 0;
            gbc.insets = new java.awt.Insets(10, 10, 10, 10); // spacing between cards
            gbc.anchor = GridBagConstraints.CENTER;

            for (TaskDto task : dayTasks) {
                JPanel card = createTaskCard(task);
                popupPanel.add(card, gbc);
                gbc.gridy++; // move to next row
            }

            // Wrap in vertical-only scroll pane
            JScrollPane scroll = new JScrollPane(popupPanel,
                    JScrollPane.VERTICAL_SCROLLBAR_AS_NEEDED,
                    JScrollPane.HORIZONTAL_SCROLLBAR_NEVER);
            scroll.setPreferredSize(new Dimension(400, 500)); // adjust size as needed
            scroll.setOpaque(false);
            scroll.getViewport().setOpaque(false);
            scroll.setBorder(null);

            // Show with GlassPanePopup
            raven.popup.DefaultOption option = new raven.popup.DefaultOption() {
                @Override
                public boolean closeWhenClickOutside() {
                    return true;
                }
            };

            raven.popup.GlassPanePopup.showPopup(
                    new raven.popup.component.SimplePopupBorder(scroll, "Tasks on " + selectedDate),
                    option
            );

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error showing tasks: " + e.getMessage());
            e.printStackTrace();
        }
    }

    // Create a modern, color-coded task card
    private JPanel createTaskCard(TaskDto task) {
        LocalDate today = LocalDate.now();
        Color statusColor;
        String statusText;

        if (task.isCompleted()) {
            statusColor = new Color(0, 180, 0); // Green
            statusText = "COMPLETED";
        } else if (task.getDeadline().isBefore(today)) {
            statusColor = new Color(220, 53, 69); // Red
            statusText = "OVERDUE";
        } else if (task.getDeadline().equals(today)) {
            statusColor = new Color(255, 193, 7); // Yellow/Orange
            statusText = "DUE TODAY";
        } else {
            statusColor = new Color(0, 123, 255); // Blue
            statusText = "UPCOMING";
        }

        // Main card panel with custom painting for rounded background and shadow
        JPanel card = new JPanel() {
            @Override
            protected void paintComponent(Graphics g) {
                Graphics2D g2 = (Graphics2D) g.create();
                g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);

                // Shadow
                g2.setColor(new Color(200, 200, 200, 80));
                g2.fillRoundRect(2, 2, getWidth() - 4, getHeight() - 4, 15, 15);

                // Background
                g2.setColor(Color.WHITE);
                g2.fillRoundRect(0, 0, getWidth() - 4, getHeight() - 4, 15, 15);
                
                // Status Strip (Left)
                g2.setColor(statusColor);
                g2.fillRoundRect(0, 0, 6, getHeight() - 4, 15, 15);
                g2.fillRect(3, 0, 3, getHeight() - 4); // Square off right side of strip

                g2.dispose();
                super.paintComponent(g); // Allow children to paint
            }
        };
        
        card.setOpaque(false);
        card.setPreferredSize(new Dimension(320, 80));
        card.setLayout(new BorderLayout(10, 0));
        card.setBorder(new EmptyBorder(10, 18, 10, 10)); // Left padding to clear strip

        // --- Center: Subject & Description ---
        JPanel centerPanel = new JPanel(new GridLayout(2, 1, 0, 2));
        centerPanel.setOpaque(false);
        
        JLabel lblSubject = new JLabel(task.getSubject());
        lblSubject.setFont(new Font("Poppins", Font.BOLD, 14));
        lblSubject.setForeground(new Color(50, 50, 50));
        
        JLabel lblDesc = new JLabel(task.getDescription() != null ? task.getDescription() : "");
        lblDesc.setFont(new Font("Poppins", Font.PLAIN, 11));
        lblDesc.setForeground(Color.GRAY);
        
        centerPanel.add(lblSubject);
        centerPanel.add(lblDesc);
        
        // --- Right: Date & Status ---
        JPanel rightPanel = new JPanel(new GridLayout(2, 1, 0, 2));
        rightPanel.setOpaque(false);
        
        JLabel lblDate = new JLabel(task.getDeadline().toString());
        lblDate.setFont(new Font("Poppins", Font.BOLD, 12));
        lblDate.setForeground(Color.DARK_GRAY);
        lblDate.setHorizontalAlignment(SwingConstants.RIGHT);
        
        JLabel lblStatus = new JLabel(statusText);
        lblStatus.setFont(new Font("Poppins", Font.BOLD, 10));
        lblStatus.setForeground(statusColor);
        lblStatus.setHorizontalAlignment(SwingConstants.RIGHT);
        
        rightPanel.add(lblDate);
        rightPanel.add(lblStatus);

        card.add(centerPanel, BorderLayout.CENTER);
        card.add(rightPanel, BorderLayout.EAST);

        return card;
    }
