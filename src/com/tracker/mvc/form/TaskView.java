    private void cmdDeleteActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_cmdDeleteActionPerformed
        try {
            if (taskController == null) {
                taskController = new TaskController();
            }

            ArrayList<Integer> rowsToDelete = new ArrayList<>();
            for (int i = 0; i < table.getRowCount(); i++) {
                Boolean selected = (Boolean) table.getValueAt(i, 1); // column 1 = checkbox
                if (selected != null && selected) {
                    rowsToDelete.add(i);
                }
            }

            if (rowsToDelete.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Please select at least one task to delete",
                        "No Selection",
                        javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                    "Are you sure you want to delete the selected task(s)?",
                    "Confirm Delete",
                    javax.swing.JOptionPane.YES_NO_OPTION);

            if (confirm != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }

            // Delete tasks
            for (int row : rowsToDelete) {
                String taskId = table.getValueAt(row, 0).toString(); // column 0 = ID
                taskController.deleteTask(taskId);
            }

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Selected task(s) deleted successfully.",
                    "Delete Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);

            loadTasksFromDB();
            notifyTaskChanged(); // Notify dashboard to refresh

        } catch (Exception ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error deleting task(s): " + ex.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }// GEN-LAST:event_cmdDeleteActionPerformed

    private void cmdNewActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_cmdNewActionPerformed
        Create createPanel = new Create();

        DefaultOption option = new DefaultOption() {
            @Override
            public boolean closeWhenClickOutside() {
                return true;
            }
        };

        String[] actions = { "Cancel", "Save" };

        GlassPanePopup.showPopup(
                new SimplePopupBorder(createPanel, "Create Task", actions, (popup, i) -> {
                    if (i == 1) { // Save
                        try {
                            String subject = createPanel.getSubject();
                            String description = createPanel.getDescription();
                            String deadlineText = createPanel.getDeadline();

                            if (subject.isEmpty() || description.isEmpty() || deadlineText.isEmpty()) {
                                javax.swing.JOptionPane.showMessageDialog(createPanel,
                                        "Please fill all fields", "Validation Error",
                                        javax.swing.JOptionPane.WARNING_MESSAGE);
                                return;
                            }

                            java.time.format.DateTimeFormatter formatter = java.time.format.DateTimeFormatter
                                    .ofPattern("dd/MM/yyyy");
                            java.time.LocalDate deadline = java.time.LocalDate.parse(deadlineText, formatter);

                            TaskDto task = new TaskDto();
                            task.setSubject(subject);
                            task.setDescription(description);
                            task.setDeadline(deadline);
                            task.setCompleted(false);

                            if (taskController == null) {
                                taskController = new TaskController();
                            }
                            String result = taskController.saveTask(task);
                            javax.swing.JOptionPane.showMessageDialog(createPanel, result);

                            loadTasksFromDB();
                            notifyTaskChanged(); // Notify dashboard to refresh
                            popup.closePopup();

                        } catch (Exception ex) {
                            ex.printStackTrace();
                            javax.swing.JOptionPane.showMessageDialog(createPanel,
                                    "Error saving task: " + ex.getMessage(), "Error",
                                    javax.swing.JOptionPane.ERROR_MESSAGE);
                        }
                    } else {
                        popup.closePopup();
                    }
                }),
                option);
    }// GEN-LAST:event_cmdNewActionPerformed

    private void cmdEditActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_cmdEditActionPerformed
        int selectedRow = table.getSelectedRow();
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please select a task to edit",
                    "No Selection",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Get task info from hidden ID column
        String taskId = table.getValueAt(selectedRow, 0).toString();
        String subject = (String) table.getValueAt(selectedRow, 3);
        String description = (String) table.getValueAt(selectedRow, 4);
        String deadlineStr = (String) table.getValueAt(selectedRow, 5);

        // Format deadline dd/MM/yyyy
        String formattedDeadline = "";
        try {
            if (deadlineStr != null && !deadlineStr.isEmpty()) {
                java.time.LocalDate deadline = java.time.LocalDate.parse(deadlineStr);
                java.time.format.DateTimeFormatter formatter = java.time.format.DateTimeFormatter
                        .ofPattern("dd/MM/yyyy");
                formattedDeadline = deadline.format(formatter);
            }
        } catch (Exception e) {
            formattedDeadline = "";
        }

        Create createPanel = new Create();
        createPanel.setTaskId(taskId);
        createPanel.setSubject(subject);
        createPanel.setDescription(description);
        createPanel.setDeadline(formattedDeadline);

        DefaultOption option = new DefaultOption() {
            @Override
            public boolean closeWhenClickOutside() {
                return true;
            }
        };

        String[] actions = { "Cancel", "Update" };

        GlassPanePopup.showPopup(
                new SimplePopupBorder(createPanel, "Edit Task", actions, (popup, i) -> {
                    if (i == 1) { // Update
                        try {
                            String newSubject = createPanel.getSubject();
                            String newDescription = createPanel.getDescription();
                            String newDeadlineText = createPanel.getDeadline();

                            if (newSubject.isEmpty() || newDescription.isEmpty()
                                    || newDeadlineText.isEmpty()
                                    || newDeadlineText.equals("--/--/----")) {
                                javax.swing.JOptionPane.showMessageDialog(createPanel,
                                        "Please enter a valid deadline",
                                        "Validation Error",
                                        javax.swing.JOptionPane.WARNING_MESSAGE);
                                return;
                            }

                            java.time.format.DateTimeFormatter formatter = java.time.format.DateTimeFormatter
                                    .ofPattern("dd/MM/yyyy");
                            java.time.LocalDate newDeadline = java.time.LocalDate.parse(newDeadlineText, formatter);

                            TaskDto task = new TaskDto();
                            task.setTaskId(createPanel.getTaskId()); // use real DB ID
                            task.setSubject(newSubject);
                            task.setDescription(newDescription);
                            task.setDeadline(newDeadline);
                            task.setCompleted(false);

                            if (taskController == null) {
                                taskController = new TaskController();
                            }
                            String result = taskController.updateTask(task);
                            javax.swing.JOptionPane.showMessageDialog(createPanel, result);

                            loadTasksFromDB();
                            notifyTaskChanged(); // Notify dashboard to refresh
                            popup.closePopup();

                        } catch (Exception ex) {
                            ex.printStackTrace();
                            javax.swing.JOptionPane.showMessageDialog(createPanel,
                                    "Error updating task: " + ex.getMessage(),
                                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                        }
                    } else {
                        popup.closePopup();
                    }
                }),
                option);
    }// GEN-LAST:event_cmdEditActionPerformed

