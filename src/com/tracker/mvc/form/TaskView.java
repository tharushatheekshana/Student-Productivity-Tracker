    private void loadTasksFromDB() {
        try {
            if (taskController == null) {
                taskController = new TaskController();
            }
            ArrayList<TaskDto> tasks = taskController.getAllTasks();
            DefaultTableModel model = new DefaultTableModel(
                    new Object[][]{},
                    new String[]{"ID", "Select", "#", "Subject", "Description", "Deadline", "Overdue", "Complete"}
            ) {
                @Override
                public Class<?> getColumnClass(int columnIndex) {
                    if (columnIndex == 1) {
                        return Boolean.class;
                    }
                    return String.class;
                }

                @Override
                public boolean isCellEditable(int row, int column) {
                    return column == 1 || column == 7;
                }
            };
            int counter = 1;
            for (TaskDto task : tasks) {
                model.addRow(new Object[]{
                    task.getTaskId(),
                    false,
                    counter++,
                    task.getSubject(),
                    task.getDescription(),
                    task.getDeadline().toString(),
                    task.isOverdue() ? "Yes" : "No",
                    task.isCompleted() ? "" : "Complete"
                });
            }
            table.setModel(model);
            table.getColumnModel().getColumn(0).setMinWidth(0);
            table.getColumnModel().getColumn(0).setMaxWidth(0);
            table.getColumnModel().getColumn(1).setHeaderRenderer(new CheckBoxTableHeaderRenderer(table, 1));
            table.getTableHeader().setDefaultRenderer(new TableHeaderAlignment(table));
            addCompleteButtonListener();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void addCompleteButtonListener() {
        table.getColumn("Complete").setCellRenderer((tbl, value, isSelected, hasFocus, row, col) -> {
            javax.swing.JButton button = new javax.swing.JButton(value == null ? "" : value.toString());
            button.setEnabled(value != null && !value.toString().isEmpty());
            return button;
        });
        table.getColumn("Complete").setCellEditor(null);

        table.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int row = table.rowAtPoint(evt.getPoint());
                int col = table.columnAtPoint(evt.getPoint());
                if (row >= 0 && col == table.getColumn("Complete").getModelIndex()) {
                    String taskId = table.getValueAt(row, 0).toString();
                    try {
                        if (taskController == null) {
                            taskController = new TaskController();
                        }
                        TaskDto task = taskController.searchTask(taskId);

                        if (!task.isCompleted()) {
                            task.setCompleted(true);
                            taskController.updateTask(task);

                            // --- GlassPanePopup Feedback ---
                            FadeLabel feedback = new FadeLabel("Well done!");
                            feedback.setOpaque(false);
                            feedback.setFont(new java.awt.Font("Poppins", 1, 28));
                            feedback.setForeground(new java.awt.Color(0, 150, 0));
                            feedback.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
                            feedback.setBounds((getWidth() - 300) / 2, 50, 300, 50); // centered

                            DefaultOption option = new DefaultOption() {
                                @Override
                                public boolean closeWhenClickOutside() {
                                    return true;
                                }
                            };

                            GlassPanePopup.showPopup(new SimplePopupBorder(feedback, "", new String[]{}, null), option);

                            // Auto fade out after 1.5 seconds
                            new javax.swing.Timer(1500, e -> GlassPanePopup.closePopup(feedback)).start();

                            // Refresh table after marking complete
                            loadTasksFromDB();
                        }
                    } catch (Exception ex) {
                        ex.printStackTrace();
                    }
                }
            }
        });
    }
